"""
Write docs/REFERENCE.md: every entry in Cursiv's offline reference, where it
comes from, when it was checked, and whether a professional has reviewed it.

    py -3.13 scripts/reference_report.py

tests/test_packs.py fails if the file is out of date, so it always matches
what ships.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "REFERENCE.md"


def render() -> str:
    sys.path[:0] = [str(REPO)]
    from cursiv_v215.core import reference as ref
    entries = sorted(ref.entries(), key=lambda e: (e.category, e.title))
    sourced = [e for e in entries if ref.source(e.title)]
    reviewed = [e for e in sourced if ref.source(e.title).get("reviewed")]
    lines = [
        "# Cursiv's offline reference",
        "",
        "Generated by `scripts/reference_report.py`; don't edit by hand.",
        "",
        f"{len(entries)} entries. {len(sourced)} are written from a named public source "
        f"(U.S. government pages, public domain); {len(entries) - len(sourced)} were written for Cursiv "
        f"without a published source (first-aid and survival ones say so on the card). {len(reviewed)} have been reviewed by a "
        "qualified professional.",
        "",
        "Entries held back from chat until reviewed: " + ", ".join(sorted(ref.NOT_IN_CHAT)) + ".",
        "",
    ]
    for cat in ref.CATEGORIES:
        rows = [e for e in entries if e.category == cat]
        lines += [f"## {cat.title()} ({len(rows)})", "", "| Entry | Source | Checked | Reviewed |", "|---|---|---|---|"]
        for e in rows:
            src = ref.source(e.title)
            if src:
                lines.append(f"| {e.title} | [{src.get('source', '')}]({src.get('url', '')}) | {src.get('checked', '')} | "
                             f"{'yes' if src.get('reviewed') else 'not yet'} |")
            else:
                lines.append(f"| {e.title} | none yet | | not yet |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"saved {OUT}")
